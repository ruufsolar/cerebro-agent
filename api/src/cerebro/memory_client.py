def _brief_from(body: dict[str, Any] | None) -> Brief:
    """An unreachable platform is an empty brief, not an exception: a bridge that
    stops answering because a memory service is restarting is worse than one that
    answers with less context."""
    if body is None:
        return Brief(text="")
    blocks = [str(body.get("stable") or ""), str(body.get("volatile") or "")]
    return Brief(
        text="\n\n".join(block for block in blocks if block),
        memory_clock=int(body.get("memory_clock") or 0),
    )


def _token_from(body: dict[str, Any]) -> _Token:
    value = str(body.get("access_token") or "")
    # Authentik always sends expires_in; a provider that does not gets a short,
    # safe window rather than a token cached forever.
    expires_in = float(body.get("expires_in") or 300)
    return _Token(value=value, expires_at=time.monotonic() + expires_in)
