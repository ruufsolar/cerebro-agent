"""A bridged agent's client for the shared memory.

Cerebro, Perestroika, Melocotón and Wattson keep their own runtimes; this is how
they read and write the store the coding sessions read. It is a single file with
no dependency but `httpx`, because it is **copied into those repositories** by
`agents export-client` rather than installed: none of them should have to take
FastAPI, Alembic and pgvector as dependencies to write one memory.

Two rules it is built around.

**A bridge never breaks because the store is down.** Every method has a value it
returns when the platform is unreachable — an empty brief, no hits, `None` — and
logs what happened. An agent that stops answering ops because a memory service
is restarting is worse than an agent that answers without the extra context.

**A bridge is its own identity.** It authenticates with its own Authentik M2M
client, and everything it writes is attributed to `m2m:<name>` by the server,
which is why nothing here can name an author.

    memory = MemoryClient.from_env("cerebro")
    if memory:
        system_prompt = memory.brief() + "\\n\\n" + system_prompt
        memory.remember("El mandato de Alza se pide antes de la evaluación")

The async twin is the same API with `await`, for a runtime that has an event
loop to protect.
"""

